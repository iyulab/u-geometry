#[test]
fn polygon_overlap_and_boundary_distance_match_shapely_in_every_unit() {
    for factor in [1.0, 1e-9, 1e6] {
        for (i, (a, b, inter, dist, _)) in PAIRS.iter().enumerate() {
            let (sa, sb) = (scaled(a, factor), scaled(b, factor));
            assert_eq!(
                polygons_intersect(&sa, &sb),
                *inter,
                "pair {i} (x{factor:e}) interiors overlap"
            );
            let d = boundary_distance(&sa, &sb).expect("non-empty");
            assert!(
                (d / factor - dist).abs() <= 1e-9 * dist.max(1.0),
                "pair {i} (x{factor:e}) boundary distance {} vs {dist}",
                d / factor
            );
        }
    }
}

/// Polygons that share an edge or a vertex do not overlap, whatever the unit.
#[test]
fn touching_polygons_do_not_overlap() {
    let square = [(0.0, 0.0), (2.0, 0.0), (2.0, 2.0), (0.0, 2.0)];
    let edge = [(2.0, 0.0), (4.0, 0.0), (4.0, 2.0), (2.0, 2.0)];
    let corner = [(2.0, 2.0), (4.0, 2.0), (4.0, 4.0), (2.0, 4.0)];
    let inside = [(0.5, 0.5), (1.5, 0.5), (1.5, 1.5), (0.5, 1.5)];
    for factor in [1.0, 0.5, 1e-9, 1e6] {
        let s = scaled(&square, factor);
        assert!(
            !polygons_intersect(&s, &scaled(&edge, factor)),
            "edge x{factor:e}"
        );
        assert!(
            !polygons_intersect(&s, &scaled(&corner, factor)),
            "corner x{factor:e}"
        );
        assert!(
            polygons_intersect(&s, &scaled(&inside, factor)),
            "nested x{factor:e}"
        );
        assert_eq!(boundary_distance(&s, &scaled(&edge, factor)), Some(0.0));
    }
}

#[test]
fn rotation_then_translation_is_a_rigid_motion() {
    let points = [(1.0, 0.0), (0.0, 2.0), (-3.0, 1.0)];
    let (angle, tx, ty) = (0.7_f64, 5.0, -2.0);
    let moved = Transform2D::new(tx, ty, angle).apply_points(&points);
    let (c, s) = (angle.cos(), angle.sin());
    for (p, m) in points.iter().zip(&moved) {
        let want = (c * p.0 - s * p.1 + tx, s * p.0 + c * p.1 + ty);
        assert!(
            (m.0 - want.0).abs() < 1e-14 && (m.1 - want.1).abs() < 1e-14,
            "{m:?} vs {want:?}"
        );
    }
    // distances between points are kept, orientation is kept
    let d = |a: (f64, f64), b: (f64, f64)| ((a.0 - b.0).powi(2) + (a.1 - b.1).powi(2)).sqrt();
    close(
        d(moved[0], moved[1]),
        d(points[0], points[1]),
        1e-14,
        "distance",
    );
    close(area(&moved), area(&points), 1e-14, "area");
}

/// The bounding box is the coordinate-wise extremes (shapely `bounds`).
#[test]
fn bounds_are_the_coordinate_extremes() {
    use u_geometry::primitives::{Point2, AABB2};
    for (i, (cloud, _)) in HULLS.iter().enumerate() {
        let points: Vec<Point2> = cloud.iter().map(|&(x, y)| Point2::new(x, y)).collect();
        let b = AABB2::from_points(&points).expect("non-empty");
        let xs = cloud.iter().map(|p| p.0);
        let ys = cloud.iter().map(|p| p.1);
        assert_eq!(
            b.min.x,
            xs.clone().fold(f64::INFINITY, f64::min),
            "hull {i} min x"
        );
        assert_eq!(
            b.max.x,
            xs.fold(f64::NEG_INFINITY, f64::max),
            "hull {i} max x"
        );
        assert_eq!(
            b.min.y,
            ys.clone().fold(f64::INFINITY, f64::min),
            "hull {i} min y"
        );
        assert_eq!(
            b.max.y,
            ys.fold(f64::NEG_INFINITY, f64::max),
            "hull {i} max y"
        );
    }
}
