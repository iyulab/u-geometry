fn close(got: f64, want: f64, rel: f64, what: &str) {
    let scale = want.abs().max(1e-300);
    assert!(
        (got - want).abs() <= rel * scale,
        "{what}: got {got}, want {want}"
    );
}

fn scaled(points: &[(f64, f64)], factor: f64) -> Vec<(f64, f64)> {
    points
        .iter()
        .map(|&(x, y)| (x * factor, y * factor))
        .collect()
}

#[test]
fn polygon_area_matches_shapely() {
    for (i, (a, _, _, _, want)) in PAIRS.iter().enumerate() {
        close(area(a), *want, 1e-12, &format!("area {i}"));
        // the unsigned area does not depend on the winding
        let reversed: Vec<(f64, f64)> = a.iter().rev().copied().collect();
        close(area(&reversed), *want, 1e-12, &format!("reversed area {i}"));
    }
}

#[test]
fn convex_hull_matches_shapely_as_a_set_and_runs_counter_clockwise_from_the_lowest_point() {
    for (i, (cloud, want)) in HULLS.iter().enumerate() {
        let hull = convex_hull(cloud);
        assert_eq!(hull.len(), want.len(), "hull {i} vertex count");
        for v in &hull {
            assert!(
                want.iter()
                    .any(|w| (w.0 - v.0).abs() < 1e-12 && (w.1 - v.1).abs() < 1e-12),
                "hull {i}: {v:?} is not on shapely's hull"
            );
        }
        // counter-clockwise, starting from the lowest point
        assert!(area(&hull) > 0.0);
        let signed: f64 = (0..hull.len())
            .map(|k| {
                let (p, q) = (hull[k], hull[(k + 1) % hull.len()]);
                p.0 * q.1 - q.0 * p.1
            })
            .sum();
        assert!(signed > 0.0, "hull {i} is clockwise");
        let lowest = hull.iter().map(|p| p.1).fold(f64::INFINITY, f64::min);
        assert_eq!(
            hull[0].1, lowest,
            "hull {i} does not start at the lowest point"
        );
    }
}

